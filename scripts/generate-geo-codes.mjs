#!/usr/bin/env node
/**
 * Generates packages/core/src/chart/geo-codes.ts: the ISO 3166-1 country table
 * (alpha-2, alpha-3, numeric, continent, English names) the choropleth matcher uses.
 *
 * Inputs are dev-only: i18n-iso-countries (MIT) for codes and alias names,
 * countries-list (MIT) for continents, world-atlas (ISC) for the names its
 * shapes carry. Run: node scripts/generate-geo-codes.mjs
 */
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const require = createRequire(import.meta.url)
const { countries: countryList } = require('countries-list')
const iso = require('i18n-iso-countries')

const atlas = JSON.parse(readFileSync(resolve(root, 'packages/core/node_modules/world-atlas/countries-110m.json'), 'utf8'))
const atlasNameById = new Map(atlas.objects.countries.geometries.filter(g => g.id).map(g => [g.id, g.properties.name]))

// Countries countries-list does not carry, or files under a different continent than analysts expect.
const CONTINENT_OVERRIDES = { XK: 'EU', AQ: 'AN', TF: 'AN', BV: 'AN', HM: 'AN', GS: 'AN', UM: 'OC' }

const rows = []
for (const [alpha2, names] of Object.entries(iso.getNames('en', { select: 'all' }))) {
  const alpha3 = iso.alpha2ToAlpha3(alpha2)
  const numeric = iso.alpha2ToNumeric(alpha2)
  const continent = CONTINENT_OVERRIDES[alpha2] ?? countryList[alpha2]?.continent
  if (!alpha3 || !numeric || !continent)
    throw new Error(`Missing data for ${alpha2}`)
  const allNames = [...names]
  const atlasName = atlasNameById.get(numeric)
  if (atlasName && !allNames.includes(atlasName))
    allNames.push(atlasName)
  rows.push([alpha2, alpha3, numeric, continent, ...allNames])
}
rows.sort((a, b) => a[0].localeCompare(b[0]))

// Written with JSON quoting; the script runs ESLint --fix afterwards for house style.
const body = rows.map(r => `  ${JSON.stringify(r)},`).join('\n')
const out = `/**
 * ISO 3166-1 countries: [alpha-2, alpha-3, numeric, continent, ...English names].
 * Generated by scripts/generate-geo-codes.mjs — do not edit by hand.
 * Continents: AF Africa, AN Antarctica, AS Asia, EU Europe, NA North America, OC Oceania, SA South America.
 */
export type CountryRow = readonly [alpha2: string, alpha3: string, numeric: string, continent: string, ...names: string[]]

export const COUNTRY_ROWS: readonly CountryRow[] = [
${body}
]
`
const target = resolve(root, 'packages/core/src/chart/geo-codes.ts')
writeFileSync(target, out)
execFileSync('pnpm', ['exec', 'eslint', '--fix', target], { cwd: root, stdio: 'inherit' })
console.log(`Wrote ${rows.length} countries`)
