/** Shared CRT treatment: monospace type, phosphor bloom, faint scanlines over the grid. */
function crtExtra(id, glow) {
  return `
.vpg-data-grid.vpg-theme-${id} {
  font-family: ${MONO};
  text-shadow: 0 0 4px ${glow};
  box-shadow: 0 0 0 1px var(--vpg-border-default), 0 0 24px -12px ${glow};
}

${squareCorners(id)}

.vpg-data-grid.vpg-theme-${id}::after {
  content: '';
  position: absolute;
  inset: 0;
  z-index: 5;
  pointer-events: none;
  background: repeating-linear-gradient(rgb(0 0 0 / 0.16) 0 1px, transparent 1px 3px);
}

@media (prefers-reduced-transparency: reduce) {
  .vpg-data-grid.vpg-theme-${id}::after {
    display: none;
  }
}`
}

function block(theme) {
  const selector = ROOTS.map(root => `${root}.vpg-theme-${theme.id}`).join(',\n')
  const tokens = Object.entries(theme.tokens).flatMap(([name, value]) => {
    const line = `  --vpg-${name}: ${value};`
    // Brand themes define focus-ring right after the accent group.
    return name === 'accent-soft-text' ? [line, '  --vpg-focus-ring: var(--vpg-accent);'] : [line]
  })
  const extra = theme.glow ? crtExtra(theme.id, theme.glow) : theme.extra?.(theme.id) ?? ''
  const rule = '='.repeat(74)
  return `/* ${rule}\n   ${theme.title}\n   ${rule} */\n${selector} {\n${tokens.join('\n')}\n}\n${extra}`.trimEnd()
}

