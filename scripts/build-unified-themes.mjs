function chrome() {
  // Two :is() groups give these rules enough weight to beat component-scoped styles.
  const scope = `:is(${ROOTS.join(', ')}):is(${themes.map(t => `.vpg-theme-${t.id}`).join(', ')})`
  const rules = chromeRules.map(([targets, declarations]) => {
    const selector = targets.map(target => `${scope} ${target}`).join(',\n')
    return `${selector} {\n${declarations.map(d => `  ${d};`).join('\n')}\n}`
  })
  const rule = '='.repeat(74)
  return `/* ${rule}\n   Shared chrome for all unified themes\n   ${rule} */\n${rules.join('\n\n')}`
}

const generated = `${MARKER}\n\n${themes.map(block).join('\n\n')}\n\n${chrome()}\n`

for (const target of TARGETS) {
  const path = resolve(ROOT, target)
  const current = readFileSync(path, 'utf-8')
  const base = current.includes(MARKER) ? current.slice(0, current.indexOf(MARKER)) : `${current.trimEnd()}\n\n`
  writeFileSync(path, base + generated)
  console.log(`wrote ${target}`)
}
